#!/usr/bin/env bash
# ============================================================
# جمعية حقّنا - HAQQUNA
# سكربت تشغيل بيئة التدريب للمتطوّعين
# ============================================================
#
# هذا السكربت يُشغّل النظام في وضع التدريب:
#   - قاعدة بيانات منفصلة (db.training.sqlite3)
#   - مجلد ميديا منفصل (media_training/)
#   - منفذ مختلف (8001 افتراضياً)
#   - جلسات مختلفة (لا تتداخل مع الإنتاج)
#   - شريط أصفر بارز يُذكّر المتطوّع أنه في بيئة تجريبية
#
# يمكن تشغيله بالتوازي مع run.sh الإنتاج:
#   - الإنتاج: ./run.sh        (المنفذ 8000)
#   - التدريب: ./run_training.sh (المنفذ 8001)
# ============================================================

set -e
cd "$(dirname "$0")"

# تفعيل وضع التدريب
export DJANGO_MODE=training

# منفذ مختلف افتراضياً
export PORT="${PORT:-8001}"

# لون مختلف للإخراج لتمييز الوضع
if [ -t 1 ]; then
    YELLOW='\033[1;33m'; BOLD='\033[1m'; NC='\033[0m'
    printf "${YELLOW}${BOLD}\n"
    cat <<'EOF'
╔══════════════════════════════════════════════════════════╗
║                                                          ║
║         ⚠  وضع التدريب — TRAINING MODE  ⚠                ║
║                                                          ║
║   قاعدة بيانات منفصلة عن الإنتاج                          ║
║   المتطوّعون يتدرّبون هنا                                  ║
║   آمن للتجريب والمسح وإعادة البدء                          ║
║                                                          ║
╚══════════════════════════════════════════════════════════╝
EOF
    printf "${NC}\n"
fi

# تشغيل run.sh العادي بمتغيرات التدريب
exec bash ./run.sh "$@"
