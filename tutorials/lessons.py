def get_lesson(lesson_id):
    """يُرجع درساً بناءً على معرّفه."""
    for lesson in LESSONS:
        if lesson["id"] == lesson_id:
            return lesson
    return None


def lessons_ordered():
    return sorted(LESSONS, key=lambda l: l["order"])
