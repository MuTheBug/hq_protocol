class Command(BaseCommand):
    help = "بذر البيانات المرجعية: مراكز الاحتجاز وأنماط التعذيب"

    def handle(self, *args, **options):
        # خريطة من كود المحافظة لاسمها العربي (للتخزين كنص للتوافق العكسي)
        gov_to_arabic = {
            "damascus": "دمشق",
            "rural_damascus": "ريف دمشق",
            "aleppo": "حلب",
            "homs": "حمص",
            "hama": "حماة",
            "latakia": "اللاذقية",
            "tartus": "طرطوس",
            "idlib": "إدلب",
            "daraa": "درعا",
            "suwayda": "السويداء",
            "quneitra": "القنيطرة",
            "raqqa": "الرقة",
            "deir_ez_zor": "دير الزور",
            "hasakah": "الحسكة",
            "": "",
        }

        created_f = 0
        for name, branch, entity, gov_code, addr in FACILITIES:
            obj, created = DetentionFacility.objects.get_or_create(
                name_ar=name,
                defaults={
                    "branch_number": branch,
                    "parent_entity": entity,
                    "governorate": gov_to_arabic.get(gov_code, gov_code),
                    "address": addr,
                },
            )
            if created:
                created_f += 1
        self.stdout.write(self.style.SUCCESS(
            f"✓ {created_f} مركز احتجاز جديد ({DetentionFacility.objects.count()} إجمالي)"
        ))

        created_t = 0
        for name_ar, category, name_en in TORTURE_METHODS:
            obj, created = TortureMethod.objects.get_or_create(
                name_ar=name_ar,
                defaults={"category": category, "name_en": name_en},
            )
            if created:
                created_t += 1
        self.stdout.write(self.style.SUCCESS(
            f"✓ {created_t} نمط تعذيب جديد ({TortureMethod.objects.count()} إجمالي)"
        ))
