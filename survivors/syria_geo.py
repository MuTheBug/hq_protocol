def cities_for(gov_code):
    """يُرجع قائمة أسماء المدن لمحافظة معينة."""
    return [city for city, _ in SYRIA_CITIES.get(gov_code, [])]


def neighborhoods_for(gov_code, city_name):
    """يُرجع قائمة الأحياء لمدينة معينة في محافظة معينة."""
    for city, neighborhoods in SYRIA_CITIES.get(gov_code, []):
        if city == city_name:
            return list(neighborhoods)
    return []


def to_js_dict():
    """يُحوّل البيانات لقاموس مناسب لـ JavaScript embedding."""
    return {
        gov: {city: neighborhoods for city, neighborhoods in cities}
        for gov, cities in SYRIA_CITIES.items()
    }
